using System.Collections.Generic;
using System.Diagnostics;
using System.Linq;
using UnityEditor;
using UnityEditor.SceneManagement;
using UnityEngine;
using UnityEngine.SceneManagement;
using Debug = UnityEngine.Debug;

namespace Blackout.Editor
{
    /// <summary>
    /// Blackout/World/Apply Materials: gives every generated bunker blockout part (Bunker/&lt;Room&gt;/&lt;Room&gt;_&lt;part&gt;)
    /// its library material, chosen by room and part name (<see cref="MaterialRules"/>), and a box mesh with UVs in
    /// world metres (<see cref="BoxUvMesh"/>) so the material's tiling is the same on every part. A part still using
    /// the cube primitive gets its own mesh, stored in the scene; a re-run rebuilds that mesh in place, so the scene is
    /// unchanged if nothing moved. Parts with any other mesh keep it, and anything not generated by the blockout is left
    /// alone. Run Build Material Library first. Build Bunker Blockout resets parts to the greybox materials, so run this
    /// again after it.
    /// Batch: Unity.exe -batchmode -nographics -quit -projectPath "..." -executeMethod Blackout.Editor.MaterialApplier.ApplyMaterials
    /// </summary>
    public static class MaterialApplier
    {
        private const string BunkerRootName = "Bunker";
        private const string UndoLabel = "Apply Materials";

        [MenuItem("Blackout/World/Apply Materials")]
        public static void ApplyMaterials()
        {
            Stopwatch timer = Stopwatch.StartNew();
            var materials = new Dictionary<string, Material>();
            foreach (SurfaceSpec spec in SurfaceLibrary.All)
            {
                var material = AssetDatabase.LoadAssetAtPath<Material>(MaterialLibraryBuilder.MaterialPath(spec.Name));
                if (material == null)
                {
                    Debug.LogError($"[World] Apply Materials stopped: {MaterialLibraryBuilder.MaterialPath(spec.Name)} is missing. "
                        + "Run Blackout/World/Build Material Library first.");
                    return;
                }

                materials.Add(spec.Name, material);
            }

            // Opens (or creates) the scene and adds any missing roots and room objects. It never removes anything.
            WorldSceneSkeleton.CreateSceneSkeleton();
            Scene scene = SceneManager.GetSceneByPath(WorldSceneSkeleton.ScenePath);
            if (!scene.IsValid() || !scene.isLoaded)
            {
                Debug.Log("[World] Apply Materials cancelled (the Environment scene is not open).");
                return;
            }

            var perSurface = new SortedDictionary<string, int>();
            int parts = 0;
            int meshes = 0;
            var skipped = new List<string>();
            foreach (Transform room in WorldSceneSkeleton.FindRoot(scene, BunkerRootName).transform)
            {
                string prefix = room.name + "_";
                foreach (Transform part in room)
                {
                    if (!part.name.StartsWith(prefix, System.StringComparison.Ordinal))
                    {
                        continue; // not generated by the blockout
                    }

                    string surface = MaterialRules.SurfaceFor(room.name, part.name.Substring(prefix.Length));
                    if (surface == null || !part.TryGetComponent(out MeshRenderer meshRenderer))
                    {
                        skipped.Add(part.name);
                        continue;
                    }

                    Undo.RecordObject(meshRenderer, UndoLabel);
                    meshRenderer.sharedMaterial = materials[surface];
                    if (part.TryGetComponent(out MeshFilter filter) && ApplyBoxMesh(filter))
                    {
                        meshes++;
                    }

                    perSurface[surface] = perSurface.TryGetValue(surface, out int count) ? count + 1 : 1;
                    parts++;
                }
            }

            EditorSceneManager.MarkSceneDirty(scene);
            EditorSceneManager.SaveScene(scene);
            string summary = string.Join(", ", perSurface.Select(pair => $"{pair.Key} {pair.Value}"));
            string skippedText = skipped.Count > 0 ? $"; skipped (no rule or renderer): {string.Join(", ", skipped)}" : string.Empty;
            Debug.Log($"[World] Materials applied in {timer.ElapsedMilliseconds} ms: {parts} bunker parts ({summary}); "
                + $"{meshes} box-UV meshes built{skippedText}.");
        }

        /// <summary>Puts a box-UV mesh on a part that has the cube primitive or its own box-UV mesh. False if it has another mesh.</summary>
        private static bool ApplyBoxMesh(MeshFilter filter)
        {
            Mesh mesh = filter.sharedMesh;
            string ownName = filter.name + BoxUvMesh.NameSuffix;
            bool own = mesh != null && mesh.name == ownName && !EditorUtility.IsPersistent(mesh);
            bool cube = mesh != null && mesh.name == "Cube" && AssetDatabase.GetAssetPath(mesh) == "Library/unity default resources";
            if (!own && !cube)
            {
                return false;
            }

            Undo.RecordObject(filter, UndoLabel);
            if (!own)
            {
                mesh = new Mesh();
                filter.sharedMesh = mesh;
            }

            BoxUvMesh.Build(mesh, filter.transform);
            return true;
        }
    }
}
