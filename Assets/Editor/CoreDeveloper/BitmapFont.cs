        public static bool Supports(char c)
        {
            return Glyphs.ContainsKey(c);
        }

        /// <summary>True when the dot at (column, row) of the glyph is lit. Row 0 is the top. Unknown characters are blank.</summary>
        public static bool IsOn(char c, int column, int row)
        {
            return Glyphs.TryGetValue(c, out string[] rows) && rows[row][column] == '1';
        }

        /// <summary>Width of a line in dots, including the gaps between letters (none after the last one).</summary>
        public static int WidthInDots(string text)
        {
            return text.Length == 0 ? 0 : text.Length * Advance - 1;
        }
