"""Prepare the user-supplied Gislinge ZIP for URP. Requires Pillow; never edits the source.

Usage: python tools/import-gislinge-boat.py D:/model/gislinge-viking-boat/source/Gislinge_Boat.zip
Then run Blackout > World > Build Rowboat Visual Assets and Replace Boat With Rowboat.
"""
import argparse
import io
from pathlib import Path
from zipfile import ZipFile

from PIL import Image, ImageOps


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("archive", type=Path)
    args = parser.parse_args()
    root = Path(__file__).resolve().parents[1]
    textures = root / "Assets/Textures/Models"
    with ZipFile(args.archive) as source:
        # Keep the author's geometry/UVs exactly as supplied; Unity handles the FBX axes/units.
        (root / "Assets/Models/Custom/SM_GislingeBoat.fbx").write_bytes(source.read("Gislinge_Boat.fbx"))

        def load(name, mode):
            return Image.open(io.BytesIO(source.read(name))).convert(mode).resize(
                (2048, 2048), Image.Resampling.LANCZOS)

        for part, prefix, base in (
            ("Hull", "Viking_Ship", "Viking_Ship_basecolor_04.jpg"),
            ("Sail", "Sailcloth", "Sailcloth_basecolor.jpg"),
        ):
            load(base, "RGB").save(textures / f"T_Gislinge_{part}_BaseColor.png")
            load(prefix + "_normal.jpg", "RGB").save(textures / f"T_Gislinge_{part}_Normal.png")
            metal = load(prefix + "_metallic.jpg", "L")
            smooth = ImageOps.invert(load(prefix + "_roughness.jpg", "L"))
            ao = load("Viking_Ship_ao.jpg", "L") if part == "Hull" else Image.new("L", metal.size, 255)
            # URP uses R for metal, G for occlusion and A for smoothness. Share this map for both slots.
            Image.merge("RGBA", (metal, ao, Image.new("L", metal.size, 0), smooth)).save(
                textures / f"T_Gislinge_{part}_MetalSmooth.png")
    print("Prepared original FBX and six 2048px maps; metadata is generated by Unity.")


if __name__ == "__main__":
    main()
